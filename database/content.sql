CREATE TABLE IF NOT EXISTS taxonomy_terms (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 site_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
 type ENUM('category','tag') NOT NULL,
 name VARCHAR(190) NOT NULL,
 slug VARCHAR(190) NOT NULL,
 UNIQUE KEY uq_term(site_id,type,slug)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS article_terms (
 article_id BIGINT UNSIGNED NOT NULL,
 term_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(article_id,term_id),
 FOREIGN KEY(article_id) REFERENCES articles(id) ON DELETE CASCADE,
 FOREIGN KEY(term_id) REFERENCES taxonomy_terms(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS article_meta (
 article_id BIGINT UNSIGNED PRIMARY KEY,
 seo_title VARCHAR(255) NOT NULL DEFAULT '',
 seo_description VARCHAR(500) NOT NULL DEFAULT '',
 canonical_url VARCHAR(1000) NOT NULL DEFAULT '',
 og_image_url VARCHAR(1000) NOT NULL DEFAULT '',
 FOREIGN KEY(article_id) REFERENCES articles(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS media_assets (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 site_id BIGINT UNSIGNED NOT NULL,
 uploader_id BIGINT UNSIGNED NULL,
 original_name VARCHAR(255) NOT NULL,
 storage_path VARCHAR(500) NOT NULL,
 mime_type VARCHAR(100) NOT NULL,
 size_bytes BIGINT UNSIGNED NOT NULL,
 alt_text VARCHAR(500) NOT NULL DEFAULT '',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY idx_media_site(site_id,created_at),
 FOREIGN KEY(site_id) REFERENCES sites(id),
 FOREIGN KEY(uploader_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS taxonomy_term_meta (
 term_id BIGINT UNSIGNED PRIMARY KEY,
 description TEXT NULL,
 parent_id BIGINT UNSIGNED NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(term_id) REFERENCES taxonomy_terms(id) ON DELETE CASCADE,
 FOREIGN KEY(parent_id) REFERENCES taxonomy_terms(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
