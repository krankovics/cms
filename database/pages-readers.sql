CREATE TABLE IF NOT EXISTS site_pages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 site_id BIGINT UNSIGNED NOT NULL,
 slug VARCHAR(190) NOT NULL,
 title VARCHAR(190) NOT NULL,
 body_html LONGTEXT NOT NULL,
 status ENUM('draft','published') NOT NULL DEFAULT 'draft',
 updated_by BIGINT UNSIGNED NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_site_page(site_id,slug),
 CONSTRAINT fk_page_site FOREIGN KEY(site_id) REFERENCES sites(id) ON DELETE CASCADE,
 CONSTRAINT fk_page_editor FOREIGN KEY(updated_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS site_readers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 site_id BIGINT UNSIGNED NOT NULL,
 email VARCHAR(190) NOT NULL,
 display_name VARCHAR(190) NOT NULL,
 password_hash VARCHAR(255) NOT NULL,
 active TINYINT(1) NOT NULL DEFAULT 1,
 failures SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 locked_until DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_reader_site_email(site_id,email),
 KEY idx_reader_site_status(site_id,active),
 FOREIGN KEY(site_id) REFERENCES sites(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;